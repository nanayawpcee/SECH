// A small .xlsx writer for the reports, so no spreadsheet library is needed.
// Supports several sheets, text and number cells, bold rows, a money format
// and column widths. Files are zipped without compression, which Excel,
// LibreOffice and Google Sheets all open.

export type XCell = string | number | null | undefined;
export type XStyle = "text" | "bold" | "money" | "moneyBold" | "title" | "muted";

export interface XRow {
  cells: XCell[];
  /** one style for the row, or one per cell */
  style?: XStyle | XStyle[];
}

export interface XSheet {
  name: string;
  rows: XRow[];
  /** column widths in characters */
  widths?: number[];
}

// fonts: 0 normal, 1 bold, 2 big bold, 3 grey
// cellXfs (style ids): 0 text, 1 bold, 2 money, 3 money bold, 4 title, 5 muted
const STYLE_ID: Record<XStyle, number> = { text: 0, bold: 1, money: 2, moneyBold: 3, title: 4, muted: 5 };

const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")
    // characters XML 1.0 doesn't allow
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "");

function colName(i: number) {
  let s = "";
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

/** Excel sheet names: 31 characters, none of []:*?/\ and unique */
function sheetNames(sheets: XSheet[]) {
  const used = new Set<string>();
  return sheets.map((s) => {
    const base = (s.name.replace(/[[\]:*?/\\]/g, " ").trim() || "Sheet").slice(0, 31);
    let name = base;
    for (let n = 2; used.has(name.toLowerCase()); n++) name = `${base.slice(0, 31 - String(n).length - 1)} ${n}`;
    used.add(name.toLowerCase());
    return name;
  });
}

function sheetXml(sheet: XSheet) {
  const cols = sheet.widths?.length
    ? `<cols>${sheet.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join("")}</cols>`
    : "";
  const rows = sheet.rows.map((row, r) => {
    const cells = row.cells.map((v, c) => {
      if (v === null || v === undefined || v === "") return "";
      const style = Array.isArray(row.style) ? row.style[c] ?? "text" : row.style ?? "text";
      const ref = `${colName(c)}${r + 1}`;
      const s = STYLE_ID[style] ? ` s="${STYLE_ID[style]}"` : "";
      if (typeof v === "number" && Number.isFinite(v)) return `<c r="${ref}"${s}><v>${v}</v></c>`;
      return `<c r="${ref}"${s} t="inlineStr"><is><t xml:space="preserve">${esc(String(v))}</t></is></c>`;
    }).join("");
    return `<row r="${r + 1}">${cells}</row>`;
  }).join("");
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${cols}<sheetData>${rows}</sheetData></worksheet>`;
}

